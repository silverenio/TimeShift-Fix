"""Generates installer payloads: for each language, the bytes that replace the tail of the
original Steam patch.s3darc (everything from the original index offset onward), plus a header
with the expected original size/CRC so the installer only patches the known file."""
import os, sys, zlib, struct
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import s3d, build_lang

ORIG = os.path.join(HERE, 'patch.s3darc.orig')
OUT = os.path.join(os.path.dirname(HERE), 'installer')
orig = open(ORIG, 'rb').read()
a = s3d.read(ORIG)
idxoff, hdrpos = a['idxoff'], a['dataoff'] - 4
crc_head = zlib.crc32(orig[:idxoff]) & 0xffffffff

for lang in ('ru', 'uk'):
    tmp = os.path.join(HERE, f'_tmp_{lang}.s3darc')
    build_lang.main(lang, ORIG, tmp)
    new = open(tmp, 'rb').read(); os.remove(tmp)
    # Only the 4-byte index offset in the header may differ before idxoff
    diff = [i for i in range(idxoff) if new[i] != orig[i]]
    assert all(hdrpos <= i < hdrpos + 4 for i in diff), diff[:10]
    new_idx = struct.unpack_from('<I', new, hdrpos)[0]
    tail = new[idxoff:]
    blob = struct.pack('<4I', new_idx, len(tail), zlib.crc32(new) & 0xffffffff, len(new)) + tail
    open(os.path.join(OUT, f'lang_{lang}.bin'), 'wb').write(blob)
    print(lang, 'tail', len(tail), 'new size', len(new))

with open(os.path.join(OUT, 'pak_info.h'), 'w') as f:
    f.write('// generated by ua/make_installer_data.py\n')
    f.write(f'#define PAK_ORIG_SIZE {len(orig)}u\n#define PAK_ORIG_CRC 0x{zlib.crc32(orig) & 0xffffffff:08x}u\n')
    f.write(f'#define PAK_IDX_OFF {idxoff}u\n#define PAK_HDR_POS {hdrpos}u\n#define PAK_HEAD_CRC 0x{crc_head:08x}u\n')
print(open(os.path.join(OUT, 'pak_info.h')).read())
